import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {resolve,dirname} from 'node:path';
import {pathToFileURL} from 'node:url';
import {createServer} from 'vite';
const localRequire=createRequire(import.meta.url);
const {svelte}=await import(pathToFileURL(resolve(dirname(localRequire.resolve('@sveltejs/kit/package.json')),'../vite-plugin-svelte/src/index.js')).href);
if(!process.env.MSL_TEST_ROOT) throw new Error('MSL_TEST_ROOT must point to an isolated directory outside the repository');
const server=await createServer({root:resolve('tests'),cacheDir:resolve(process.env.MSL_TEST_ROOT,'stability/vite'),configFile:false,plugins:[svelte({configFile:false})],resolve:{alias:{$lib:resolve('src/lib')}},server:{host:'127.0.0.1',port:1442,strictPort:true,fs:{allow:[resolve('.')]},watch:{ignored:['**/src-tauri/**','**/.test-runtime/**']}}});
await server.listen();
const runtime=process.env.MSL_NODE_MODULES;
if(!runtime) throw new Error('MSL_NODE_MODULES is required');
const {chromium}=createRequire(resolve(runtime,'runtime.cjs'))('playwright');
const browser=await chromium.launch({channel:'msedge',headless:true});
console.log('Browser started');
const page=await browser.newPage({viewport:{width:1280,height:800}});
page.setDefaultTimeout(15000);
page.on('pageerror',e=>console.error(e.message));
try {
 await page.goto('http://127.0.0.1:1442/layout.html');
 const button=page.getByTestId('subject'),neighbor=page.getByTestId('neighbor');
 await button.waitFor();
 const before=await button.boundingBox(), next=await neighbor.boundingBox();
 await page.locator('#loading').click();
 const after=await button.boundingBox();
 assert.ok(Math.abs(after.width-before.width)<=1,`Loading changed button width ${before.width} -> ${after.width}`);
 assert.ok(Math.abs((await neighbor.boundingBox()).x-next.x)<=1,'Loading moved adjacent control');
 await page.locator('#loading').click();await button.hover();await page.waitForTimeout(200);
 assert.ok(Math.abs((await button.boundingBox()).y-before.y)<=1,'Hover moved button');
 const anchor=await page.locator('#anchor').boundingBox();
 await page.locator('#notify').click();
 assert.ok(Math.abs((await page.locator('#anchor').boundingBox()).y-anchor.y)<=1,'Notification shifted page');
 await page.locator('#dismiss').click();
 await page.locator('#modal').click();await page.locator('#last').focus();await page.keyboard.press('Tab');
 assert.ok(await page.locator('[role=dialog]').evaluate(e=>e.contains(document.activeElement)),'Tab escaped modal');
 await page.keyboard.press('Escape');await page.waitForTimeout(30);
 assert.equal(await page.locator('#modal').evaluate(e=>e===document.activeElement),true,'Modal did not restore focus');
 console.log('PASS stable loading, hover, notifications, focus trapping and restoration');
 if(process.argv.includes('--delete')){
  await page.locator('#delete-open').click();
  const confirm=page.getByTestId('typed-delete-confirm'),name=page.getByTestId('typed-delete-name');
  assert.equal(await confirm.isDisabled(),true);
  await name.fill('错误名称');assert.equal(await confirm.isDisabled(),true);
  await name.fill(' 测试专家 ');assert.equal(await confirm.isEnabled(),true);
  await name.dispatchEvent('compositionstart');assert.equal(await confirm.isDisabled(),true);
  await name.dispatchEvent('compositionend');await confirm.click();
  assert.equal(await page.locator('#deleted').textContent(),'deleted');
  await page.keyboard.press('Escape');await page.locator('#delete-open').click();
  assert.equal(await name.inputValue(),'','Confirmation must reset on reopen');
  console.log('PASS typed deletion rejects wrong names/IME and clears confirmation on reopen');
 }
 if(process.argv.includes('--catalog')){
  await page.goto('http://127.0.0.1:1442/catalog.html');
  await page.getByTestId('connection-1-api-key').waitFor();
  assert.equal(await page.locator('.model-row:visible').count(),0,'Provider model list should start collapsed');
  await page.getByTestId('models-fold-1').click();
  await page.getByTestId('model-toggle-1').waitFor();
  const rect=await page.getByTestId('model-toggle-1').boundingBox();
  await page.getByTestId('model-toggle-1').click();await page.waitForTimeout(400);
  assert.equal(await page.locator('.model-row:visible').count(),12,'Toggle must preserve expansion');
  const updated=await page.getByTestId('model-toggle-1').boundingBox();
  assert.ok(Math.abs(updated.width-rect.width)<=1&&Math.abs(updated.y-rect.y)<=1,'Model toggle moved');
  await page.reload();await page.getByTestId('model-toggle-1').waitFor();
  await page.goto('http://127.0.0.1:1442/catalog.html?qa');
  await page.getByTestId('qa-session-1').click();await page.getByTestId('qa-turn-1').waitFor();
  await page.getByTestId('qa-session-2').click();
  assert.equal(await page.locator('.qa-welcome').count(),0,'Switching session flashed the welcome screen');
  await page.getByTestId('qa-session-1').click();
  await page.getByTestId('qa-turn-1').waitFor();await page.waitForTimeout(500);
  assert.equal(await page.getByTestId('qa-turn-2').count(),0,'Stale result replaced active conversation');
  const transcript=page.getByTestId('qa-transcript');
  await transcript.evaluate(el=>el.scrollTop=120);await page.waitForTimeout(100);
  const reading=await transcript.evaluate(el=>el.scrollTop);assert.ok(reading>0,'Long synthetic answer must overflow');
  await page.waitForTimeout(2500);
  assert.ok(Math.abs(await transcript.evaluate(el=>el.scrollTop)-reading)<=1,'Polling forced history to bottom');
  await page.getByTestId('qa-session-2').click();await page.getByTestId('qa-turn-2').waitFor();
  await page.getByTestId('qa-session-1').click();await page.getByTestId('qa-turn-1').waitFor();await page.waitForTimeout(150);
  assert.ok(Math.abs(await transcript.evaluate(el=>el.scrollTop)-reading)<=1,'Switching back lost reading position');
  const composer=await page.getByTestId('qa-composer').boundingBox();
  await page.getByTestId('qa-question').fill('@');
  assert.ok(Math.abs((await page.getByTestId('qa-composer').boundingBox()).y-composer.y)<=1,'Project picker moved composer');
  console.log('PASS provider folding/persistence/stable toggles, conversation loading and stale result guards');
 }
} catch(e) {console.error(e);process.exitCode=1;} finally {await browser.close();await server.close();}
